// Invoked by personal-workspaces.cjs against disposable PostgreSQL only.
const assert = require('node:assert/strict');
module.exports = async function testDailyQuestions(db, ids, couple) {
  const scalar = async (sql,args=[]) => Object.values((await db.query(sql,args)).rows[0])[0];
  const user = async id => {
    await db.exec('reset role');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);
    await db.exec('set role authenticated');
  };
  const state = () => scalar('select public.daily_question_state()');
  const prefs = patch => db.query('select public.set_question_preferences($1)',[JSON.stringify(patch)]);
  await user(ids[0]);
  assert.equal((await state()).questions.length,0);
  await assert.rejects(db.query('select * from public.daily_question_answers'),/permission denied/);
  await assert.rejects(db.query('select public.enqueue_daily_questions()'),/permission denied/);
  await prefs({enabled:true,introduced:true});
  assert.equal((await state()).active,false);
  await db.query("select public.set_question_schedule('00:00','Europe/Minsk')");
  await assert.rejects(db.query("select public.set_question_schedule('25:90','Wrong/Zone')"),/Проверьте/);
  await assert.rejects(prefs({intimate:true}),/18 лет/);
  await user(ids[1]);
  await prefs({enabled:true,introduced:true});
  let next = await state();
  assert.equal(next.time,'00:00');
  assert.equal(next.active,true);
  assert.equal(next.questions.length,1);
  const question = next.questions[0];
  assert.equal(question.intimate,false);
  assert.equal((await state()).questions[0].id,question.id,'question is stable');
  await db.exec('reset role; set role service_role');
  await db.query('select public.enqueue_daily_questions()');
  await db.query('select public.enqueue_daily_questions()');
  await db.exec('reset role');
  assert.equal(await scalar('select count(*)::int from public.wish_jobs where daily_question_id=$1',[question.id]),2);
  await user(ids[0]);
  await db.query('select public.answer_daily_question($1,$2)',[question.id,'SECRET-FIRST-ANSWER']);
  await user(ids[1]);
  next = await state();
  assert.equal(JSON.stringify(next).includes('SECRET-FIRST-ANSWER'),false,'partner cannot read first answer');
  assert.equal(next.questions[0].answered_count,1);
  assert.equal(JSON.stringify(await scalar('select public.daily_question_detail($1)',[question.id])).includes('SECRET-FIRST-ANSWER'),false);
  await prefs({enabled:false});
  await db.exec('reset role; set role service_role');
  assert.equal(await scalar('select public.daily_question_delivery($1,$2)',[question.id,ids[1]]),null,'pause suppresses queued delivery');
  await user(ids[1]);
  await prefs({enabled:true,push_enabled:false});
  await db.exec('reset role; set role service_role');
  assert.equal(await scalar('select public.daily_question_delivery($1,$2)',[question.id,ids[1]]),null);
  await user(ids[1]);
  await prefs({push_enabled:true});
  await db.exec('reset role; set role service_role');
  assert.equal(await scalar('select public.daily_question_delivery($1,$2)',[question.id,ids[1]]),question.body);
  await user(ids[1]);
  await db.query('select public.answer_daily_question($1,$2)',[question.id,'SECOND-ANSWER']);
  next = await state();
  assert.equal(next.questions[0].revealed,true);
  assert.equal(next.questions[0].answers.length,2);
  assert.equal((await scalar('select public.daily_question_detail($1)',[question.id])).answers.length,2);
  await assert.rejects(db.query('select public.answer_daily_question($1,$2)',[question.id,'overwrite']),/закрыты/);
  await user(ids[2]);
  assert.equal((await state()).questions.length,0);
  assert.equal(await scalar('select public.daily_question_detail($1)',[question.id]),null);
  await assert.rejects(db.query('select public.answer_daily_question($1,$2)',[question.id,'intruder']),/Нет доступа/);
  // Synthetic next day with an intimate question, without changing any production clock.
  await db.exec('reset role');
  await db.query('update public.couple_daily_questions set day=day-1 where id=$1',[question.id]);
  await db.query('update public.daily_questions set active=intimate');
  await user(ids[0]);
  await prefs({intimate:true,adult_confirmed:true});
  assert.equal((await state()).intimate_active,false);
  assert.equal((await state()).questions.length,1,'one consent cannot assign intimate question');
  await user(ids[1]);
  await prefs({intimate:true,adult_confirmed:true});
  next = await state();
  assert.equal(next.intimate_active,true);
  const intimate = next.questions[0];
  assert.equal(intimate.intimate,true);
  await db.exec('reset role; set role service_role');
  assert.equal(await scalar('select public.daily_question_delivery($1,$2)',[intimate.id,ids[0]]),'Для вас новый личный вопрос');
  await user(ids[0]);
  await db.query('select public.answer_daily_question($1,$2)',[intimate.id,'PRIVATE-ANSWER']);
  await user(ids[1]);
  await prefs({intimate:false});
  next = await state();
  assert.equal(next.preferences.intimate,false,'toggle changes current account');
  await user(ids[0]);
  assert.equal((await state()).preferences.intimate,true,'partner preference must remain enabled');
  await user(ids[1]);
  assert.equal(next.questions[0].cancelled,true);
  assert.equal(JSON.stringify(next).includes('PRIVATE-ANSWER'),false);
  await assert.rejects(db.query('select public.answer_daily_question($1,$2)',[intimate.id,'late']),/закрыты/);
  assert.equal(next.questions.find(q=>q.id===question.id).answers.length,2,'revealed history remains');
  await db.exec('reset role; set role service_role');
  assert.equal(await scalar('select public.daily_question_delivery($1,$2)',[intimate.id,ids[0]]),null);
  await db.exec('reset role');
  // A skipped ordinary question never reveals a previously submitted answer.
  await db.query('update public.couple_daily_questions set day=day-2 where id=$1',[intimate.id]);
  await db.query('update public.daily_questions set active=not intimate');
  await user(ids[0]);
  const skipped = (await state()).questions[0];
  await db.query('select public.answer_daily_question($1,$2)',[skipped.id,'UNREVEALED']);
  await user(ids[1]);
  await db.query("select public.answer_daily_question($1,'',true)",[skipped.id]);
  next = await state();
  assert.equal(next.questions[0].skipped,true);
  assert.equal(JSON.stringify(next).includes('UNREVEALED'),false);
  await db.exec('reset role');
  await db.query(`insert into public.couple_daily_questions(couple_id,question_id,day,body,intimate)
    select $1,$2,current_date-n,'Исторический вопрос '||n,false from generate_series(10,54) n`,[couple,question.question_id ?? await scalar('select question_id from public.couple_daily_questions where id=$1',[question.id])]);
  await user(ids[0]);
  const first = await state();
  assert.equal(first.questions.length,20);
  assert.equal(first.has_more,true);
  const second = await scalar('select public.daily_question_history($1)',[first.questions.at(-1).day]);
  assert.equal(second.questions.length,20);
  assert.equal(second.has_more,true);
  const third = await scalar('select public.daily_question_history($1)',[second.questions.at(-1).day]);
  assert.equal(third.questions.length,8);
  assert.equal(third.has_more,false);
  assert.equal(new Set([...first.questions,...second.questions,...third.questions].map(q=>q.id)).size,48);
  await user(ids[2]);
  assert.equal((await scalar('select public.daily_question_history(null)')).questions.length,0);
  await db.exec('reset role');
  console.log('PASS: daily question privacy, consent, delivery, and history pagination 20/20/8 without duplicates');
};
